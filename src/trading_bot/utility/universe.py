nifty150_ns: list[str] = [f"{t}.NS" for t in nifty150]
nifty50_ns: list[str] = [f"{t}.NS" for t in nifty50]
nifty250_ns: list[str] = [f"{t}.NS" for t in nifty250]

UNIVERSE_MAP: dict[str, set[str]] = {
    "N50": set(nifty50_ns),
    "N150": set(nifty150_ns),
    "N250": set(nifty250_ns),
}

UNIVERSES: list[tuple[str, list[str]]] = [
    ("N50", nifty50_ns),
    ("N150", nifty150_ns),
    ("N250", nifty250_ns),
]


def normalize_ticker(raw_ticker: str) -> str:
    """Normalize ticker string to ensure uppercase and .NS suffix."""
    ticker = raw_ticker.strip().upper()
    if not ticker.endswith(".NS"):
        ticker = f"{ticker}.NS"
    return ticker


def detect_universe(ticker: str) -> str:
    """Detect the index universe membership for a given ticker."""
    normalized = normalize_ticker(ticker)
    memberships = [name for name, tickers in UNIVERSE_MAP.items() if normalized in tickers]
    return ", ".join(memberships) if memberships else "Custom"
